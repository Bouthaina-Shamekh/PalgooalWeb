<?php

namespace App\Services\Domains;

use App\Models\Domain;
use App\Models\DomainProvider;
use App\Models\DomainTld;
use App\Models\Invoice;
use App\Models\Order;
use App\Services\Domains\Exceptions\MissingRenewalPriceException;
use Carbon\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Str;

class DomainRenewalService
{
    public function prepareRenewalCheckout(Domain $domain, int $years = 1, bool $autoGenerated = false): array
    {
        $domain->loadMissing('client');

        if (!$autoGenerated) {
            $existingInvoice = $this->findPendingRenewalInvoice($domain);
            if ($existingInvoice instanceof Invoice) {
                return [
                    'invoice' => $existingInvoice->loadMissing(['items', 'order.items']),
                    'created' => false,
                    'eligible' => true,
                ];
            }
        }

        $years = max(1, $years);

        return DB::transaction(function () use (
            $domain,
            $years,
            $autoGenerated,
        ) {
            $lockedDomain = Domain::query()->lockForUpdate()->findOrFail($domain->id);

            if ($autoGenerated && !$this->isDueForAutoRenewal($lockedDomain)) {
                return [
                    'invoice' => null,
                    'created' => false,
                    'eligible' => false,
                ];
            }

            $existingInvoice = $this->findPendingRenewalInvoice($lockedDomain);

            if ($existingInvoice instanceof Invoice) {
                return [
                    'invoice' => $existingInvoice->loadMissing(['items', 'order.items']),
                    'created' => false,
                    'eligible' => true,
                ];
            }

            [$currentRenewalDate, $nextRenewalDate] = $this->buildRenewalWindow($lockedDomain, $years);
            $quote = $this->buildRenewalQuote($lockedDomain, $years);

            $order = Order::create([
                'client_id' => $lockedDomain->client_id,
                'status' => Order::STATUS_PENDING,
                'type' => 'domain_renewal',
                'notes' => 'Domain renewal order for ' . $lockedDomain->domain_name,
            ]);

            $order->items()->create([
                'domain' => $lockedDomain->domain_name,
                'item_option' => 'renew',
                'price_cents' => $quote['price_cents'],
                'meta' => [
                    'currency' => $quote['currency'],
                    'registrar' => $lockedDomain->registrar ?: $this->defaultRegistrarType(),
                    'domain_id' => $lockedDomain->id,
                    'current_renewal_date' => $currentRenewalDate->toDateString(),
                    'renewal_date' => $nextRenewalDate->toDateString(),
                    'term_years' => $years,
                    'auto_generated' => $autoGenerated,
                ],
            ]);

            $invoice = Invoice::create([
                'client_id' => $lockedDomain->client_id,
                'order_id' => $order->id,
                'number' => $this->generateUniqueInvoiceNumber(),
                'status' => 'unpaid',
                'subtotal_cents' => $quote['price_cents'],
                'total_cents' => $quote['price_cents'],
                'currency' => $quote['currency'],
                'due_date' => $currentRenewalDate->toDateString(),
            ]);

            $invoice->items()->create([
                'item_type' => 'domain',
                'reference_id' => $lockedDomain->id,
                'description' => 'Domain Renewal: ' . $lockedDomain->domain_name,
                'qty' => 1,
                'unit_price_cents' => $quote['price_cents'],
                'total_cents' => $quote['price_cents'],
            ]);

            return [
                'invoice' => $invoice->loadMissing(['items', 'order.items']),
                'created' => true,
                'eligible' => true,
            ];
        });
    }

    public function processDueAutoRenewals(bool $dryRun = false): array
    {
        $summary = [
            'scanned' => 0,
            'due' => 0,
            'created' => 0,
            'existing' => 0,
            'renewed' => 0,
            'awaiting_payment' => 0,
            'failed' => 0,
            'details' => [],
        ];

        $domains = Domain::query()
            ->where('auto_renew', true)
            ->whereNotNull('renewal_date')
            ->whereIn('status', ['active', 'pending', 'expired'])
            ->with('client')
            ->orderBy('renewal_date')
            ->get();

        foreach ($domains as $domain) {
            $summary['scanned']++;

            if (!$this->isDueForAutoRenewal($domain)) {
                continue;
            }

            $summary['due']++;

            try {
                if ($dryRun) {
                    $pendingInvoice = $this->findPendingRenewalInvoice($domain);
                    $quote = $this->buildRenewalQuote($domain, 1);

                    $summary['details'][] = [
                        'domain' => $domain->domain_name,
                        'renewal_date' => Carbon::parse($domain->renewal_date)->toDateString(),
                        'provider' => strtolower((string) ($domain->registrar ?: $this->defaultRegistrarType())),
                        'estimated_price_cents' => $quote['price_cents'],
                        'currency' => $quote['currency'],
                        'pending_invoice' => $pendingInvoice instanceof Invoice,
                        'action' => $pendingInvoice instanceof Invoice
                            ? 'awaiting_payment'
                            : 'create_unpaid_invoice',
                    ];

                    continue;
                }

                $checkout = $this->prepareRenewalCheckout($domain, 1, true);

                if (!($checkout['eligible'] ?? true)) {
                    continue;
                }

                $invoice = $checkout['invoice'];

                if ($checkout['created']) {
                    $summary['created']++;
                } else {
                    $summary['existing']++;
                }

                $awaitingPaymentMessage = strtr(
                    t(
                        'client.domains.auto_renew_invoice_awaiting_payment',
                        'Auto-renew invoice #:invoice is ready and awaiting payment.'
                    ),
                    [':invoice' => $invoice->number],
                );

                $domain->forceFill([
                    'dns_last_note' => $awaitingPaymentMessage,
                ])->save();

                $summary['awaiting_payment']++;
            } catch (MissingRenewalPriceException $e) {
                $registrar = strtolower((string) ($domain->registrar ?: $this->defaultRegistrarType()));
                $tld = $this->extractTld($domain->domain_name);

                Log::warning('Auto-renew skipped: no trusted renewal sale price for domain.', [
                    'domain_id' => $domain->id,
                    'domain' => $domain->domain_name,
                    'registrar' => $registrar,
                    'tld' => $tld,
                    'reason' => 'missing_renewal_sale',
                    'error' => $e->getMessage(),
                ]);

                if (!$dryRun) {
                    $domain->forceFill([
                        'dns_last_note' => t(
                            'client.domains.auto_renew_price_unavailable',
                            'Auto-renew skipped: no trusted renewal price (sale) is currently available for this domain.'
                        ),
                    ])->save();
                }

                $summary['failed']++;
            } catch (\Throwable $e) {
                Log::error('Auto-renew processing failed', [
                    'domain_id' => $domain->id,
                    'domain' => $domain->domain_name,
                    'error' => $e->getMessage(),
                ]);

                if (!$dryRun) {
                    $failureMessage = strtr(
                        t(
                            'client.domains.auto_renew_invoice_failed',
                            'Auto-renew invoice preparation failed: :error'
                        ),
                        [':error' => Str::limit($e->getMessage(), 180)],
                    );

                    $domain->forceFill([
                        'dns_last_note' => $failureMessage,
                    ])->save();
                }

                $summary['failed']++;
            }
        }

        return $summary;
    }

    public function findPendingRenewalInvoice(Domain $domain): ?Invoice
    {
        return Invoice::query()
            ->where('client_id', $domain->client_id)
            ->whereIn('status', ['draft', 'unpaid'])
            ->where(function ($query) use ($domain) {
                $query->whereHas('order.items', function ($items) use ($domain) {
                    $items->where('domain', $domain->domain_name)
                        ->where('item_option', 'renew');
                })->orWhereHas('items', function ($items) use ($domain) {
                    $items->where('item_type', 'domain')
                        ->where('reference_id', $domain->id)
                        ->where('description', 'like', 'Domain Renewal:%');
                });
            })
            ->latest('id')
            ->first();
    }

    public function isDueForAutoRenewal(Domain $domain, ?Carbon $today = null): bool
    {
        if (!$domain->auto_renew || empty($domain->renewal_date)) {
            return false;
        }

        $today = ($today ?: now())->copy()->startOfDay();
        $renewalDate = Carbon::parse($domain->renewal_date)->startOfDay();
        $startDate = $renewalDate->copy()->subDays($this->leadDaysFor($domain));

        return $today->greaterThanOrEqualTo($startDate);
    }

    public function leadDaysFor(Domain $domain): int
    {
        $registrar = strtolower((string) ($domain->registrar ?: $this->defaultRegistrarType()));
        $tld = $this->extractTld($domain->domain_name);

        if ($registrar === 'enom') {
            return 30;
        }

        if (in_array($tld, [
            'ch',
            'es',
            'com.es',
            'nom.es',
            'org.es',
            'fr',
            'li',
            'pe',
            'com.pe',
            'net.pe',
            'org.pe',
            'sg',
            'com.sg',
            'com.au',
            'net.au',
            'org.au',
        ], true)) {
            return 12;
        }

        if (in_array($tld, ['cx', 'de', 'eu', 'nl'], true)) {
            return 5;
        }

        return 7;
    }

    protected function buildRenewalWindow(Domain $domain, int $years = 1): array
    {
        $currentRenewalDate = $domain->renewal_date
            ? Carbon::parse($domain->renewal_date)->startOfDay()
            : now()->startOfDay()->addYear();

        $nextRenewalDate = $currentRenewalDate->copy()->addYears(max(1, $years));

        return [$currentRenewalDate, $nextRenewalDate];
    }

    /**
     * TLD-3B — Strict Sale-Only Renewal Pricing.
     *
     * يقبل حصراً renew.sale الصريح والرقمي والأكبر من صفر، لنفس الـTLD ونفس
     * المزوّد (provider) الفعّال الذي يحمل النطاق حالياً. لا يوجد أي fallback:
     * لا renew.cost، لا register.sale، لا register.cost، ولا أي قيمة ثابتة
     * (hard-coded). أي إخفاق في تحقيق هذا الشرط يوقف العملية فوراً برمي
     * MissingRenewalPriceException — ولا يُعاد أبداً سعر اصطناعي (synthetic).
     */
    protected function buildRenewalQuote(Domain $domain, int $years = 1): array
    {
        $registrar = strtolower((string) ($domain->registrar ?: $this->defaultRegistrarType()));
        $tld = $this->extractTld($domain->domain_name);
        $years = max(1, $years);

        $row = DomainTld::query()
            ->with([
                'prices' => fn ($query) => $query
                    ->where('action', 'renew')
                    ->where('years', $years),
            ])
            ->where('enabled', true)
            ->whereIn('tld', [$tld, '.' . $tld])
            ->whereHas('provider', function ($query) use ($registrar) {
                $query->active()->where('type', $registrar);
            })
            ->first();

        $sale = $row?->prices->first()?->sale;

        if ($sale === null || $sale === '' || !is_numeric($sale) || (float) $sale <= 0) {
            throw new MissingRenewalPriceException(sprintf(
                'Missing trusted renew.sale price for domain [%s], tld [%s], registrar [%s], years [%d].',
                $domain->domain_name,
                $tld,
                $registrar,
                $years,
            ));
        }

        $currency = strtoupper(trim((string) ($row->currency ?? '')));

        if ($currency === '' || !preg_match('/^[A-Z]{3}$/', $currency)) {
            throw new MissingRenewalPriceException(sprintf(
                'Invalid or missing renewal currency for domain [%s], tld [%s], registrar [%s].',
                $domain->domain_name,
                $tld,
                $registrar,
            ));
        }

        return [
            'price_cents' => (int) round(((float) $sale) * 100),
            'currency' => $currency,
        ];
    }

    protected function extractTld(string $domainName): string
    {
        $normalized = strtolower(trim($domainName));

        if (!str_contains($normalized, '.')) {
            return '';
        }

        $parts = explode('.', $normalized, 2);

        return ltrim($parts[1] ?? '', '.');
    }

    protected function defaultRegistrarType(): string
    {
        return DomainProvider::query()
            ->active()
            ->whereIn('type', ['namecheap', 'enom'])
            ->orderByRaw("CASE WHEN type = 'namecheap' THEN 0 WHEN type = 'enom' THEN 1 ELSE 2 END")
            ->value('type') ?? 'namecheap';
    }

    protected function generateUniqueInvoiceNumber(): string
    {
        do {
            $number = 'INV-' . Str::upper(Str::random(6));
        } while (Invoice::where('number', $number)->exists());

        return $number;
    }
}
